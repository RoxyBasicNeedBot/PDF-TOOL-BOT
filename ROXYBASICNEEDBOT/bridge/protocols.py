from dataclasses import dataclass, asdict
import json

@dataclass
class BridgeMessage:
    type: str          # "file_relay", "status_query", "action_sync"
    sender_id: int
    recipient_id: int
    payload: dict
    timestamp: float

    def to_json(self) -> str:
        return json.dumps(asdict(self))

    @classmethod
    def from_json(cls, data_str: str):
        data = json.loads(data_str)
        return cls(**data)
